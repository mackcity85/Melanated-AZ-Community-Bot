    now = datetime.now(ZoneInfo("America/Phoenix")).isoformat()
    conn = sqlite3.connect(db_path, timeout=30)
    try:
        conn.execute("PRAGMA busy_timeout=30000")
        conn.execute("BEGIN IMMEDIATE")
        seeded = conn.execute(
            "SELECT value FROM qotd_meta WHERE key='default_200_bank_seeded_v1'"
        ).fetchone()
        if seeded:
            conn.commit()
            return 0
        cur = conn.executemany(
            """INSERT INTO qotd_items
               (item_type, prompt, options_json, submitted_by, submitted_name, created_at, status)
               VALUES ('question', ?, NULL, NULL, ?, ?, 'queued')""",
            [(item['question'], 'Melanated AZ Question Bank — ' + item['category'], now)
             for item in QUESTION_BANK],
        )
        conn.execute(
            "INSERT INTO qotd_meta(key,value) VALUES('default_200_bank_seeded_v1',?)",
            (now,),
        )
        conn.commit()
        return len(QUESTION_BANK)
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()
